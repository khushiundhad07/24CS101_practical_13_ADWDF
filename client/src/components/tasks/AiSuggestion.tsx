interface AiSuggestionProps {
  text: string;
  onChange: (text: string) => void;
  onAccept: () => void;
  onDismiss: () => void;
}

/** An editable AI suggestion. Nothing is used until the user reviews it and chooses "Use this". */
export default function AiSuggestion({ text, onChange, onAccept, onDismiss }: AiSuggestionProps) {
  return (
    <div className="mt-3 rounded-xl border border-rust/30 bg-rust-soft/40 p-4">
      <div className="flex items-center gap-2">
        <span className="rounded bg-rust px-1.5 py-0.5 font-mono text-[10.5px] font-semibold uppercase tracking-wider text-rust-ink">AI</span>
        <p className="text-[13px] font-medium">Suggested description</p>
      </div>
      <textarea
        value={text}
        onChange={(e) => onChange(e.target.value)}
        rows={3}
        aria-label="Suggested description (editable)"
        className="mt-3 w-full resize-y rounded-lg border border-line bg-paper-raised px-3 py-2 text-[14.5px] outline-none focus:border-rust"
      />
      <p className="mt-2 text-[12.5px] text-ink-soft">
        Generated by AI from the task title. It may be inaccurate — read and edit it before saving.
      </p>
      <div className="mt-3 flex gap-2">
        <button type="button" onClick={onAccept} className="rounded-lg bg-ink px-3.5 py-1.5 text-[13.5px] font-semibold text-paper hover:bg-rust hover:text-rust-ink">
          Use this
        </button>
        <button type="button" onClick={onDismiss} className="rounded-lg px-3 py-1.5 text-[13.5px] text-ink-soft hover:bg-paper-sunk">
          Dismiss
        </button>
      </div>
    </div>
  );
}
